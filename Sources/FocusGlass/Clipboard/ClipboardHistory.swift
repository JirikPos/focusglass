import AppKit
import Observation

/// Posledních 10 zkopírovaných textů. Jen v paměti (nic se neukládá na disk)
/// a hesla ze správců hesel se ignorují.
///
/// macOS neposílá notifikaci o změně schránky, proto se 1× za ~1,5 s porovná
/// jediné číslo (`changeCount`) – zanedbatelná zátěž.
@MainActor
@Observable
final class ClipboardHistory {
    struct Item: Identifiable, Equatable {
        let id = UUID()
        let text: String
    }

    private static let limit = 10
    /// Typy, které správci hesel a podobné aplikace používají pro citlivý obsah.
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    private(set) var items: [Item] = []
    /// Položka, která se právě zkopírovala zpět (pro potvrzení v UI).
    private(set) var justCopied: Item.ID?

    @ObservationIgnored private var changeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var timer: Timer?

    func setEnabled(_ enabled: Bool) {
        timer?.invalidate()
        timer = nil
        guard enabled else {
            items.removeAll()
            return
        }
        changeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: 1.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.5
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func copy(_ item: Item) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(item.text, forType: .string)
        changeCount = pasteboard.changeCount
        items.removeAll { $0 == item }
        items.insert(item, at: 0)
        justCopied = item.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.2) { [weak self] in
            MainActor.assumeIsolated {
                if self?.justCopied == item.id { self?.justCopied = nil }
            }
        }
    }

    func clear() {
        items.removeAll()
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes),
              let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }

        items.removeAll { $0.text == text }
        items.insert(Item(text: text), at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
    }
}
